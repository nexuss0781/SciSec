"""AES-128/192/256 from scratch (FIPS 197).

The S-box is *derived* at import time: every byte is mapped to its
multiplicative inverse in GF(2^8) (with 0 -> 0) and then passed through
the affine transformation

    s = b ^ rotl8(b,1) ^ rotl8(b,2) ^ rotl8(b,3) ^ rotl8(b,4) ^ 0x63

which is exactly the FIPS 197 definition.  The round constants are
generated by repeated multiplication by x in GF(2^8).  Nothing is
hard-coded except the Rijndael polynomial x^8+x^4+x^3+x+1 (0x11B).
"""

from __future__ import annotations

import struct


def _xtime(a: int) -> int:
    a <<= 1
    if a & 0x100:
        a ^= 0x11B
    return a


def _gf_mul(a: int, b: int) -> int:
    out = 0
    while b:
        if b & 1:
            out ^= a
        a = _xtime(a)
        b >>= 1
    return out


def _gf_inv(a: int) -> int:
    """Multiplicative inverse in GF(2^8); 0 maps to 0 (FIPS 197 rule)."""
    if a == 0:
        return 0
    # a^254 == a^-1 in the multiplicative group of order 255.
    result = 1
    base = a
    exp = 254
    while exp:
        if exp & 1:
            result = _gf_mul(result, base)
        base = _gf_mul(base, base)
        exp >>= 1
    return result


def _rotl8(x: int, n: int) -> int:
    return ((x << n) | (x >> (8 - n))) & 0xFF


def _build_sbox() -> tuple[tuple[int, ...], tuple[int, ...]]:
    sbox = []
    for a in range(256):
        b = _gf_inv(a)
        s = b ^ _rotl8(b, 1) ^ _rotl8(b, 2) ^ _rotl8(b, 3) ^ _rotl8(b, 4) ^ 0x63
        sbox.append(s)
    inv = [0] * 256
    for i, v in enumerate(sbox):
        inv[v] = i
    return tuple(sbox), tuple(inv)


SBOX, INV_SBOX = _build_sbox()

# Round constants: rcon[i] = x^(i-1) in GF(2^8), starting at 1.
RCON = [0x01]
for _ in range(1, 14):
    RCON.append(_xtime(RCON[-1]))

N_K = {16: 4, 24: 6, 32: 8}
N_R = {16: 10, 24: 12, 32: 14}


def _sub_word(word: bytes) -> bytes:
    return bytes(SBOX[b] for b in word)


def _rot_word(word: bytes) -> bytes:
    return word[1:] + word[:1]


class AES:
    """AES block cipher with 128-, 192- or 256-bit keys."""

    def __init__(self, key: bytes) -> None:
        if len(key) not in N_K:
            raise ValueError("AES key must be 16, 24 or 32 bytes")
        self.key_size = len(key)
        self.nk = N_K[len(key)]
        self.nr = N_R[len(key)]
        self.round_keys = self._expand(key)

    def _expand(self, key: bytes) -> list[bytes]:
        nk, nr = self.nk, self.nr
        words = [key[4 * i : 4 * i + 4] for i in range(nk)]
        for i in range(nk, 4 * (nr + 1)):
            temp = words[i - 1]
            if i % nk == 0:
                temp = _sub_word(_rot_word(temp))
                temp = bytes([temp[0] ^ RCON[i // nk - 1], temp[1], temp[2], temp[3]])
            elif nk > 6 and i % nk == 4:
                temp = _sub_word(temp)
            words.append(bytes(a ^ b for a, b in zip(words[i - nk], temp)))
        return [b"".join(words[4 * r : 4 * r + 4]) for r in range(nr + 1)]

    # -- round transforms (state is a flat 16-byte column-major array) --

    @staticmethod
    def _add_round_key(state: list[int], rk: bytes) -> None:
        for i in range(16):
            state[i] ^= rk[i]

    @staticmethod
    def _sub_bytes(state: list[int]) -> None:
        for i in range(16):
            state[i] = SBOX[state[i]]

    @staticmethod
    def _inv_sub_bytes(state: list[int]) -> None:
        for i in range(16):
            state[i] = INV_SBOX[state[i]]

    @staticmethod
    def _shift_rows(state: list[int]) -> None:
        # state[r + 4c]; row r rotates left by r positions.
        for r in range(1, 4):
            row = [state[r + 4 * c] for c in range(4)]
            row = row[r:] + row[:r]
            for c in range(4):
                state[r + 4 * c] = row[c]

    @staticmethod
    def _inv_shift_rows(state: list[int]) -> None:
        for r in range(1, 4):
            row = [state[r + 4 * c] for c in range(4)]
            row = row[-r:] + row[:-r]
            for c in range(4):
                state[r + 4 * c] = row[c]

    @staticmethod
    def _mix_columns(state: list[int]) -> None:
        for c in range(4):
            i = 4 * c
            a0, a1, a2, a3 = state[i : i + 4]
            state[i] = _xtime(a0) ^ (_xtime(a1) ^ a1) ^ a2 ^ a3
            state[i + 1] = a0 ^ _xtime(a1) ^ (_xtime(a2) ^ a2) ^ a3
            state[i + 2] = a0 ^ a1 ^ _xtime(a2) ^ (_xtime(a3) ^ a3)
            state[i + 3] = (_xtime(a0) ^ a0) ^ a1 ^ a2 ^ _xtime(a3)

    @staticmethod
    def _inv_mix_columns(state: list[int]) -> None:
        for c in range(4):
            i = 4 * c
            a0, a1, a2, a3 = state[i : i + 4]
            state[i] = (
                _gf_mul(a0, 14) ^ _gf_mul(a1, 11) ^ _gf_mul(a2, 13) ^ _gf_mul(a3, 9)
            )
            state[i + 1] = (
                _gf_mul(a0, 9) ^ _gf_mul(a1, 14) ^ _gf_mul(a2, 11) ^ _gf_mul(a3, 13)
            )
            state[i + 2] = (
                _gf_mul(a0, 13) ^ _gf_mul(a1, 9) ^ _gf_mul(a2, 14) ^ _gf_mul(a3, 11)
            )
            state[i + 3] = (
                _gf_mul(a0, 11) ^ _gf_mul(a1, 13) ^ _gf_mul(a2, 9) ^ _gf_mul(a3, 14)
            )

    def encrypt_block(self, block: bytes) -> bytes:
        if len(block) != 16:
            raise ValueError("AES block must be 16 bytes")
        state = list(block)
        self._add_round_key(state, self.round_keys[0])
        for r in range(1, self.nr):
            self._sub_bytes(state)
            self._shift_rows(state)
            self._mix_columns(state)
            self._add_round_key(state, self.round_keys[r])
        self._sub_bytes(state)
        self._shift_rows(state)
        self._add_round_key(state, self.round_keys[self.nr])
        return bytes(state)

    def decrypt_block(self, block: bytes) -> bytes:
        if len(block) != 16:
            raise ValueError("AES block must be 16 bytes")
        state = list(block)
        self._add_round_key(state, self.round_keys[self.nr])
        for r in range(self.nr - 1, 0, -1):
            self._inv_shift_rows(state)
            self._inv_sub_bytes(state)
            self._add_round_key(state, self.round_keys[r])
            self._inv_mix_columns(state)
        self._inv_shift_rows(state)
        self._inv_sub_bytes(state)
        self._add_round_key(state, self.round_keys[0])
        return bytes(state)


def _xor_bytes(a: bytes, b: bytes) -> bytes:
    return bytes(x ^ y for x, y in zip(a, b))


def ctr_xor(key: bytes, nonce_counter: bytes, data: bytes) -> bytes:
    """AES-CTR with a 16-byte big-endian counter block (FIPS 197 App. B)."""
    aes = AES(key)
    out = bytearray()
    counter = int.from_bytes(nonce_counter, "big")
    blocks = (len(data) + 15) // 16
    for i in range(blocks):
        keystream = aes.encrypt_block((counter + i & (2**128 - 1)).to_bytes(16, "big"))
        chunk = data[16 * i : 16 * i + 16]
        out.extend(x ^ y for x, y in zip(chunk, keystream))
    return bytes(out)
